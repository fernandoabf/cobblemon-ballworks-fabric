#!/usr/bin/env python3
"""Derives the 3D models of the pieces shown on the anvils from Cobblemon's own 3D Poke Ball models.

Cobblemon draws a held Poke Ball with a Java block model (models/item/poke_ball_model.json, or
ancient_poke_ball_model.json for the Hisuian balls): two 8x4x8 halves, each with an inflated outer
layer, plus the button (and, on the ancient balls, the plate, port, bumps and latch). Here:

  piece/lid.json, piece/ancient_lid.json   the elements of the top half (centre above the seam),
                                           without the button/latch: what the anvil turns a disc into
  piece/<ball>_lid.json                    that geometry with the ball's own texture, referenced from
                                           Cobblemon (cobblemon:item/poke_balls/models/<ball>_ball)
  piece/iron_base.json                     the bottom half, with textures/item/piece/iron_base.png:
                                           Cobblemon's Poke Ball texture recoloured to iron

The renderer draws a disc as the same model squashed flat and lets it rise into the dome stage by
stage, so one model per ball covers every stage. The geometry and the iron texture are derivative
works of Cobblemon's assets (c) The Cobblemon Team, distributed under Cobblemon's license (MPL-2.0).

Usage (from the repository root, needs Pillow):
    python3 tools/derive_piece_models.py
"""
import glob
import io
import json
import sys
import zipfile
from pathlib import Path

from PIL import Image, PngImagePlugin

# Same list and order as com.xaiver.cobbleballworks.content.ForgeBall.
BALLS = [
    "poke", "great", "ultra", "level", "moon", "friend", "love", "safari", "heavy", "fast", "repeat",
    "timer", "nest", "net", "dive", "luxury", "heal", "dusk", "premier", "sport", "quick", "lure",
    "citrine", "verdant", "azure", "roseate", "slate",
    "park", "dream", "beast", "master", "cherish",
    "ancient_poke", "ancient_great", "ancient_ultra", "ancient_heavy", "ancient_leaden",
    "ancient_gigaton", "ancient_feather", "ancient_wing", "ancient_jet", "ancient_ivory",
    "ancient_citrine", "ancient_verdant", "ancient_azure", "ancient_roseate", "ancient_slate",
    "ancient_origin",
]

SEAM = 4.0  # y of the line between the two halves in Cobblemon's models
MODELS = Path("src/main/resources/assets/cobbleballworks/models/piece")
TEXTURES = Path("src/main/resources/assets/cobbleballworks/textures/item/piece")
BASE_GEOMETRY = {
    "cobblemon:item/poke_ball_model": "lid",
    "cobblemon:item/ancient_poke_ball_model": "ancient_lid",
}
CREDIT = (
    "Derived from Cobblemon's {source} (c) The Cobblemon Team, MPL-2.0 (https://mozilla.org/MPL/2.0/). "
    "Generated by tools/derive_piece_models.py in github.com/fernandoabf/cobblemon-ballworks-fabric."
)
# Iron: Cobblemon's white bottom half (four light tones, a dark rim and a red-brown inside) mapped
# onto a cool steel ramp: the light tones spread from STEEL_SHADE to STEEL_LIGHT, the rest darkens.
STEEL_LIGHT = (0xCB, 0xD1, 0xD7)
STEEL_SHADE = (0x6E, 0x75, 0x7C)
STEEL_DARK = (0x2C, 0x30, 0x34)


def model_path(ref):
    namespace, path = ref.split(":")
    return f"assets/{namespace}/models/{path}.json"


def centre_y(element):
    return (element["from"][1] + element["to"][1]) / 2


def half(model, top):
    """The elements whose centre is above (top) or below the seam; the button sits on it."""
    keep = (lambda c: c > SEAM + 1e-3) if top else (lambda c: c < SEAM - 1e-3)
    elements = [e for e in model["elements"] if keep(centre_y(e))]
    if not top:  # the ancient latch and plates also hang below the seam; the base is plain
        elements = [e for e in elements if e.get("name", "").startswith("bottom_") and "rim" not in e["name"]]
    for e in elements:
        for face in e["faces"].values():
            face["texture"] = "#layer0"
    return elements


def geometry(model, source, top, texture=None):
    out = {
        "credit": CREDIT.format(source=source),
        "texture_size": model.get("texture_size", [64, 32]),
        "textures": {"particle": "#layer0"},
        "elements": half(model, top),
    }
    if texture:
        out["textures"]["layer0"] = texture
    return out


def iron(texture):
    """Recolours the bottom-half regions (x >= 32) of a 64x32 ball texture to iron; drops the rest."""
    out = Image.new("RGBA", texture.size, (0, 0, 0, 0))
    for y in range(texture.size[1]):
        for x in range(texture.size[0] // 2, texture.size[0]):
            r, g, b, a = texture.getpixel((x, y))
            if a == 0:
                continue
            luma = (r * 299 + g * 587 + b * 114) / 1000 / 255
            if luma >= 0.6:
                colour = mix(STEEL_SHADE, STEEL_LIGHT, min(1.0, (luma - 0.6) / 0.33))
            else:
                colour = mix(STEEL_DARK, STEEL_SHADE, luma / 0.6)
            out.putpixel((x, y), colour + (a,))
    return out


def mix(a, b, t):
    return tuple(round(ca + (cb - ca) * t) for ca, cb in zip(a, b))


def write_json(path, data):
    path.write_text(json.dumps(data, indent=2) + "\n")


def main():
    jars = sorted(glob.glob("run-libs/Cobblemon-fabric-*.jar"))
    if not jars:
        sys.exit("Cobblemon jar not found in run-libs/ (run ./gradlew build once to download it)")
    MODELS.mkdir(parents=True, exist_ok=True)
    TEXTURES.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(jars[-1]) as jar:
        def load(ref):
            return json.loads(jar.read(model_path(ref)))

        for ref, name in BASE_GEOMETRY.items():
            write_json(MODELS / f"{name}.json", geometry(load(ref), ref.split("/")[-1] + ".json", top=True))

        for ball in BALLS:
            parent = load(f"cobblemon:item/{ball}_ball_model").get("parent", f"cobblemon:item/{ball}_ball_model")
            if parent not in BASE_GEOMETRY:
                sys.exit(f"{ball}: unexpected 3D model parent {parent}")
            write_json(MODELS / f"{ball}_lid.json", {
                "parent": f"cobbleballworks:piece/{BASE_GEOMETRY[parent]}",
                "textures": {"layer0": f"cobblemon:item/poke_balls/models/{ball}_ball"},
            })

        poke = load("cobblemon:item/poke_ball_model")
        write_json(MODELS / "iron_base.json",
                   geometry(poke, "poke_ball_model.json", top=False, texture="cobbleballworks:item/piece/iron_base"))
        texture = Image.open(io.BytesIO(jar.read("assets/cobblemon/textures/item/poke_balls/models/poke_ball.png")))
        info = PngImagePlugin.PngInfo()
        info.add_text("Copyright", CREDIT.format(source="poke_ball.png (recoloured to iron)"))
        iron(texture.convert("RGBA")).save(TEXTURES / "iron_base.png", pnginfo=info, optimize=True)
    print(f"wrote {len(BASE_GEOMETRY) + len(BALLS) + 1} piece models and the iron texture from {jars[-1]}")


if __name__ == "__main__":
    main()
